#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const packageRoot = process.env.CODEAGENT_FEATURE_PACKAGES_ROOT
  ? path.resolve(process.env.CODEAGENT_FEATURE_PACKAGES_ROOT)
  : path.resolve(repoRoot, '..', 'code-agent-packages');
const packageDistRoot = process.env.CODEAGENT_FEATURE_PACKAGE_DIST_ROOT
  ? path.resolve(process.env.CODEAGENT_FEATURE_PACKAGE_DIST_ROOT)
  : path.join(packageRoot, 'dist-feature-packages');
const outDir = path.join(repoRoot, 'src', 'features', 'package-catalog');
const outFile = path.join(outDir, 'generated.ts');
const rendererOutDir = path.join(repoRoot, 'src', 'features', 'package-renderers');
const rendererOutFile = path.join(rendererOutDir, 'generated.ts');

function readJson(filePath) {
  return JSON.parse(readFileSync(filePath, 'utf8'));
}

function discoverPackageManifests() {
  if (!existsSync(packageRoot)) {
    return [];
  }

  return readdirSync(packageRoot, { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .map(entry => path.join(packageRoot, entry.name, 'manifest.json'))
    .filter(manifestPath => existsSync(manifestPath))
    .map(manifestPath => readJson(manifestPath))
    .sort((left, right) => String(left.id).localeCompare(String(right.id)));
}

function discoverRendererModules() {
  if (!existsSync(packageRoot)) return [];
  return readdirSync(packageRoot, { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .map(entry => ({
      packageDir: path.join(packageRoot, entry.name),
      manifestPath: path.join(packageRoot, entry.name, 'manifest.json'),
    }))
    .filter(entry => existsSync(entry.manifestPath))
    .map(entry => ({ ...entry, manifest: readJson(entry.manifestPath) }))
    .filter(entry => Boolean(entry.manifest.entrypoints?.renderer))
    .map(entry => ({
      packageId: String(entry.manifest.id),
      modulePath: path.join(
        packageDistRoot,
        String(entry.manifest.id),
        String(entry.manifest.entrypoints.renderer),
      ),
    }))
    .map(entry => {
      if (!existsSync(entry.modulePath)) {
        throw new Error(`Renderer artifact for ${entry.packageId} is missing: ${entry.modulePath}. Build feature packages first.`);
      }
      return entry;
    })
    .sort((left, right) => left.packageId.localeCompare(right.packageId));
}

function moduleSpecifier(fromDir, targetPath) {
  const relativePath = path.relative(fromDir, targetPath).split(path.sep).join('/');
  return relativePath.startsWith('.') ? relativePath : `./${relativePath}`;
}

const manifests = discoverPackageManifests();
mkdirSync(outDir, { recursive: true });

const source = [
  "import type { FeaturePackageManifest } from '@codeagent/feature-package-sdk';",
  '',
  '// Generated by scripts/generate-feature-package-catalog.mjs. Do not edit by hand.',
  'export const EXTERNAL_FEATURE_PACKAGE_CATALOG_MANIFESTS: FeaturePackageManifest[] = ',
  `${JSON.stringify(manifests, null, 2)} as FeaturePackageManifest[];`,
  '',
].join('\n');

writeFileSync(outFile, source);

const rendererModules = discoverRendererModules();
mkdirSync(rendererOutDir, { recursive: true });
const rendererSource = [
  "import type { FeaturePackageRendererModule } from '@codeagent/feature-package-sdk';",
  ...rendererModules.map((entry, index) => (
    `import renderer${index} from ${JSON.stringify(moduleSpecifier(rendererOutDir, entry.modulePath))};`
  )),
  '',
  '// Generated by scripts/generate-feature-package-catalog.mjs. Do not edit by hand.',
  'export const EXTERNAL_FEATURE_PACKAGE_RENDERER_MODULES: FeaturePackageRendererModule[] = [',
  ...rendererModules.map((_entry, index) => `  renderer${index},`),
  '];',
  '',
].join('\n');
writeFileSync(rendererOutFile, rendererSource);

console.log(`Generated ${path.relative(repoRoot, outFile)} with ${manifests.length} package manifest(s).`);
console.log(`Generated ${path.relative(repoRoot, rendererOutFile)} with ${rendererModules.length} renderer module(s).`);
